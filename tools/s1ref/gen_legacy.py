#!/usr/bin/env python3
"""Generate EngineCore/LegacyTables.hpp from reference/meta/legacy.json
(measure_legacy.py): the original's conversion of old-version patches.

Groups (exact version numbers; a .sy1 without a ver line loads as 100):
  100       = everything of 105 + attack / sustain / gain / velocity / LFO
              speed / osc2 fine tables + params 67..72 forced
  105, 106  = decay / release, filter amount, delay level, chorus, wheel
              sens, params 75..98 forced
  107, 108  = wheel sens, unison detune 75, params 91..98 forced
Special cases kept out of the generic maps (handled in Sy1Codec.hpp):
wheel sens 50 / 51 (formula on the raw lfo1 depth / speed), unison detune 75
and voice num 93 (depend on play mode 38)."""
import json

import s1

META = s1.ROOT / "reference/meta/legacy.json"
OUT = s1.ROOT / "EngineCore/LegacyTables.hpp"
GROUPS = {"100": (100,), "105": (105, 106), "107": (107, 108)}
SPECIAL = {"50", "51", "75", "93"}
# midi ctrl routing 86..89 (1.09+): forced to the init routing in every
# legacy group (probed: s1ref fromnative ver=100 / 105 / 107 86=.. 89=..)
ROUTING = {86: 45057, 87: 44, 88: 45057, 89: 43}


def main():
    data = json.loads(META.read_text())
    ver = data["versions"]
    for a, b in (("105", "106"), ("107", "108")):
        assert ver[a] == ver[b], f"{a} != {b}"
    tables = []

    def table_index(t):
        if t not in tables:
            tables.append(t)
        return tables.index(t)

    rules = {}  # (param, table, value) -> group mask
    for bit, g in enumerate(GROUPS):
        items = dict(ver[g])
        items.update({str(p): [v] for p, v in ROUTING.items()})  # measured separately (all groups)
        for p, t in items.items():
            if p in SPECIAL:
                continue
            if len(set(t)) == 1:
                key = (int(p), -1, t[0])
            else:
                assert len(t) == 128, p
                key = (int(p), table_index(t), 0)
            rules[key] = rules.get(key, 0) | 1 << bit
    pm = data["play_mode"]
    for g in ("105", "107"):
        for i in ("75", "93"):
            assert pm[g][i]["1"] == pm[g][i]["2"]
    uni_poly = table_index(pm["107"]["75"]["0"])
    uni_mono = table_index(pm["107"]["75"]["1"])
    assert set(pm["105"]["75"]["0"]) == {48} and set(pm["105"]["75"]["1"]) == {70}
    assert set(pm["105"]["93"]["0"]) == {2} and set(pm["105"]["93"]["1"]) == {4}
    assert set(pm["107"]["93"]["0"]) == {2} and set(pm["107"]["93"]["1"]) == {4}

    rows = []
    for t in tables:
        body = ",\n".join("        " + ", ".join(f"{v:3d}" for v in t[i : i + 16]) for i in range(0, 128, 16))
        rows.append("    {\n" + body + ",\n    },")
    out = [
        "#pragma once\n",
        "// GENERATED by tools/s1ref/gen_legacy.py from reference/meta/legacy.json —",
        "// the original Synth1's conversion of old-version patches (measured through",
        "// its state chunk version word, identical to its .sy1 loader). Do not edit.\n",
        "#include <cstdint>\n",
        "namespace oxo::s2::legacy {\n",
        "// version groups (bit masks)",
        "enum : uint8_t { kVer100 = 1, kVer105 = 2, kVer107 = 4 };\n",
        "// table >= 0: new = kTables[table][old]; table < 0: the old version lacked",
        "// the param, it is set to `value` whatever the file holds.",
        "struct Rule {\n    int8_t param, table;\n    int32_t value;\n    uint8_t groups;\n};\n",
        f"inline constexpr uint8_t kTables[{len(tables)}][128] = {{",
        *rows,
        "};\n",
        "inline constexpr Rule kRules[] = {",
    ]
    names = {1: "kVer100", 2: "kVer105", 4: "kVer107"}
    for (p, t, v), mask in sorted(rules.items()):
        groups = " | ".join(names[b] for b in (1, 2, 4) if mask & b)
        out.append(f"    {{{p}, {t}, {v}, {groups}}},")
    out += [
        "};\n",
        "// ver 107 / 108 unison detune 75 (old knob law) per play mode 38: 0 poly, 1 / 2 mono",
        f"inline constexpr int kUnisonDetunePoly = {uni_poly}, kUnisonDetuneMono = {uni_mono};\n",
        "} // namespace oxo::s2::legacy\n",
    ]
    OUT.write_text("\n".join(out))
    print("wrote", OUT, len(tables), "tables")


if __name__ == "__main__":
    main()
