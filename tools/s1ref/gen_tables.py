#!/usr/bin/env python3
"""Generate EngineCore/MeasuredTables.hpp from reference/meta/*.json.

Every table is indexed by the native knob value (0..127) and holds a
quantity measured on the original Synth1 renders (see the measure_*.py
scripts and tools/s1ref/README.md). Re-run after any re-measurement."""
import json

import numpy as np

import s1

META = s1.ROOT / "reference/meta"
OUT = s1.ROOT / "EngineCore/MeasuredTables.hpp"


def load(name):
    return json.loads((META / name).read_text())


def cfloat(v):
    s = "{:.7g}".format(v)
    if not any(c in s for c in ".e"):
        s += ".0"
    return s + "f"


def table(name, values, comment, fmt=None, ctype="float"):
    rows = []
    conv = cfloat if fmt is None else fmt.format
    for i in range(0, len(values), 8):
        rows.append("    " + ", ".join(conv(v) for v in values[i : i + 8]) + ",")
    return f"// {comment}\ninline constexpr {ctype} {name}[{len(values)}] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    env = load("amp_env.json")
    gv = load("amp_gain_vel.json")
    pitch = load("osc_pitch.json")
    fm = load("fm.json")
    ladder = load("filter_ladder_law.json")
    sat = load("filter_sat.json")
    fmod = load("filter_mod.json")
    lfo = load("lfo_depth.json")
    lfo_keysync = load("lfo_keysync.json")["s1"]
    uni = load("unison.json")
    uni_det = [float(np.interp(v, uni["vals"], uni["detune_cents"])) for v in range(128)]
    slot = load("slot_phase.json")
    porta = load("porta.json")
    eq_tone = load("eq_tone.json")["hz"]
    delay_tone = load("delay_tone.json")["hz"]
    porta_tau = [0.0] + [float(np.exp(np.interp(v, porta["vals"], np.log(porta["tau"])))) for v in range(1, 128)]
    pc = list(lfo["pitch_cents"])
    # the old estimator broke down near full depth: the key-synced
    # measurement (measure_lfo_keysync.py) covers 112..127
    for d, c in zip(lfo_keysync["pitch_hi_depths"], lfo_keysync["pitch_hi_cents"]):
        pc[d] = c
    fxm = load("effect.json")
    dl = load("filter_lpdl.json")
    vol = load("volume.json")["gain"]
    vol[0] = 0.0
    dl_rows = [dl["fits"][str(r)] for r in dl["res"]]  # [res][cut step] = [c, w, k, g, err]
    dl_w = [row[1] for rows in dl_rows for row in rows]
    dl_k = [row[2] for rows in dl_rows for row in rows]
    dl_g = [row[3] for rows in dl_rows for row in rows]
    vs = fmod["vel_switch"]
    vel_scale = [max(0.0, float(np.interp(v, vs["vel"], vs["scale"]))) for v in range(128)]

    attack = env["attack_s"]
    attack[0] = 0.0005  # v=0 reads 0.6 ms through the demodulator; the law gives 0.5 ms
    decay = env["decay_tau"]
    sustain = env["sustain"]
    sustain[0] = 0.0
    gain = [g / gv["gain"][64] for g in gv["gain"]]  # relative to knob 64
    semis = [int(round(s)) for s in pitch["osc2_pitch_semis"]]
    fine = [int(round(c)) for c in pitch["osc2_fine_cents"]]

    ad1 = fxm["ad1"]
    ad1_drive = [ad1["drive64"] * 10 ** (3.5 * (c - 64) / 127) for c in range(128)]
    ad1_out = [ad1["out64"] * o for o in fxm["ad1_law"]["out"]]
    parts = [
        "#pragma once\n",
        "// GENERATED by tools/s1ref/gen_tables.py from reference/meta/*.json —",
        "// measurements of the original Synth1. Do not edit by hand.\n",
        "namespace oxo::s2::tables {\n",
        table("kAmpAttackSeconds", attack, "amp env attack: linear ramp time to full scale (s)"),
        table("kEnvTauSeconds", decay, "amp env decay/release exponential time constant (s); release == decay law"),
        table("kAmpSustainLevel", sustain, "amp env sustain level (linear, 127 = 1)"),
        table("kAmpGain", gain, "amp gain knob, linear, relative to knob 64"),
        table("kOsc2PitchSemis", semis, "osc2 pitch knob -> semitones", "{:d}", "int"),
        table("kFineCents", fine, "osc2 fine / osc1,2 tune knob -> cents (dead zone 62..66)", "{:d}", "int"),
        table("kFmBeta", fm["beta"], "osc1 FM: inst_freq1 = f1 * (1 + beta * osc2_normalized)"),
        table("kLadderCutoffHz", ladder["fc"], "LP24 ladder stage cutoff (Hz) per cutoff knob"),
        table("kLadderFeedbackComp", ladder["kcomp"],
              "LP24 feedback k = (0.0297 * res - 0.076) * comp[cutoff] (keeps the delayed loop stable)"),
        table("kSaturationA", sat["alg_a"], "filter saturation y = (1 + a) x / (1 + a |x|), a per sat knob"),
        table("kKbdTrack", fmod["kbd_track_factor"], "filter kbd track: cutoff octaves per key octave (pivot key 48)"),
        table("kLfoPitchCents", pc, "LFO -> pitch: amplitude in cents per depth knob"),
        table("kUnisonDetuneCents", uni_det, "unison: voices spread evenly over +-D cents"),
        table("kEqToneHz", eq_tone, "EQ tone: bilinear one-pole cutoff (Hz, no prewarp); <= 64 lowpass (64 = 22 kHz), > 64 highpass"),
        table("kDelayToneHz", delay_tone, "delay tone: bilinear one-pole cutoff (Hz); < 64 lowpass, 64 = none, > 64 highpass"),
        table("kPortaTau", porta_tau, "portamento: glide time constant (s) per knob, 0 = off (16-sample steps, see Voice)"),
        table("kSlotOsc1Phase", slot["osc1"], "osc phase 0: initial osc1 phase (cycles) of voice slot 0..31"),
        table("kSlotOsc2Phase", slot["osc2"], "osc phase 0: initial osc2 phase (cycles) of voice slot 0..31"),
        table("kSlotCopyPhase", [v for row in slot["copies"] for v in row],
              "osc phase 0: initial osc1 detune copy phases (cycles), [slot 0..31][copy, offsets -7..7]"),
        table("kFilterVelScale", vel_scale, "filter env amount scale per velocity when the velocity switch is on"),
        table("kLpdlW", dl_w, "LPDL stage rate w (rad/s), [res 0,16,..,112,127][cutoff 0,4,..,124]"),
        table("kLpdlK", dl_k, "LPDL feedback k (high-passed at 100 Hz), same grid"),
        table("kLpdlG", dl_g, "LPDL output gain, same grid"),
        table("kAd1Drive", ad1_drive, "effect a.d.1 drive per ctl1: fit_ad1.py drive64 x 10^(3.5 (ctl1 - 64) / 127) (measure_ad1_law.py)",
              fmt="{:.9g}", ctype="double"),
        table("kAd1Out", ad1_out, "effect a.d.1 output gain per ctl1: fit_ad1.py out64 x the measured law (measure_ad1_law.py)",
              fmt="{:.9g}", ctype="double"),
        table("kAd2Drive", fxm["drive"]["1"], "effect a.d.2 drive gain per ctl1 = 0, 4, .., 124, 127"),
        table("kDdSlope", fxm["dd_slope"], "effect d.d. fold slope per ctl1 (measure_dd.py)", fmt="{:.9g}", ctype="double"),
        table("kDdPeak", fxm["dd_peak"], "effect d.d. fold peak per ctl1 (measure_dd.py)", fmt="{:.9g}", ctype="double"),
        table("kAd2Curve", fxm["ad2_curve"], "effect a.d.2 transfer F(u), odd, u = 0 .. 10 step 0.05, flat above"),
        table("kVolumeGain", vol, "master vol knob (chunk word 651, not a parameter), linear, relative to 64"),
        "} // namespace oxo::s2::tables\n",
    ]
    OUT.write_text("\n".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
